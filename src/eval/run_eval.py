"""The single command that regenerates the whole V1 evaluation package.

    python -m src.eval.run_eval

Reads only the committed C3/C5/C6 artifacts under `results/v1/inputs/`, so
it runs on a clean clone with no dataset, no GPU and no checkpoint
(PLAN.md §12: "regenerates from stored predictions with one command").

Kept generic over run id and split so V2-V5 reuse it unchanged (PLAN.md §10
lists the eval suite as a V1 artifact consumed by every later version).
"""
