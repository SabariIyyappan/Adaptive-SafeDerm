        "",
        "Class proportions deviate from train by at most **0.081 pp at the lesion level** (what",
        "`train_test_split(stratify=dx)` acts on) and **0.806 pp at the image level**. Zero lesions and",
        "zero images are shared between splits, all 7 classes appear in all 3 splits, and mean",
        "images-per-lesion is near-identical across them. A perceptual-hash sweep with pixel",
        "verification found no duplicate images crossing splits. Full detail in `data_report.md`.",
        "",
        "## 4. Diagnostics: why the model over-predicts melanoma",
        "",
        f"Melanoma specificity is **{mel['specificity']:.3f}** against the paper's "
        f"{F.PAPER_MEL_SPECIFICITY:.3f}, while sensitivity is close "
        f"({mel['recall']:.3f} vs {F.PAPER_MEL_SENSITIVITY:.3f}). "
