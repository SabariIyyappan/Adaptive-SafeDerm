def run(inputs_dir: Path, out_dir: Path, run_id: str, seed: int,
        n_resamples: int, split_dir: Path) -> None:
    figures_dir = out_dir / "figures"
    tables_dir = out_dir / "tables"

    test_df = load_predictions(inputs_dir / "predictions_test.csv")
    val_df = load_predictions(inputs_dir / "predictions_val.csv")
    history = pd.read_csv(inputs_dir / "history.csv")
    checkpoint = json.loads((inputs_dir / "checkpoint.json").read_text())
    best_epoch = int(checkpoint.get("best_epoch", history["epoch"].iloc[-1]))

    test_probs, test_true = probs_and_labels(test_df)
    val_probs, val_true = probs_and_labels(val_df)

    print(f"Evaluating {run_id}: {len(test_df):,} test / {len(val_df):,} val predictions")

    metrics = macro_metrics(test_true, test_probs)
    val_metrics = macro_metrics(val_true, val_probs)
    per_class = per_class_table(test_true, test_probs)
    val_per_class = per_class_table(val_true, val_probs)
    ece, _ = expected_calibration_error(test_true, test_probs)
    brier = brier_score(test_true, test_probs)
    confidence = confidence_summary(test_true, test_probs)

    print(f"  macro AUROC {metrics['macro_auroc']:.4f} · macro F1 {metrics['macro_f1']:.4f}")
    print(f"  bootstrapping {n_resamples:,} resamples (seed {seed})...")
    boot = bootstrap_metrics(test_true, test_probs, n_resamples=n_resamples, seed=seed)

    print("  writing figures...")
    F.plot_training_curves(history, figures_dir / "training_curves.png", best_epoch=best_epoch)
    F.plot_confusion_matrix(test_true, test_probs, figures_dir / "confusion_matrix.png")
    F.plot_per_class_accuracy(per_class, figures_dir / "per_class_accuracy.png")
    F.plot_per_class_sens_spec(per_class, figures_dir / "per_class_sens_spec.png")
    F.plot_roc_curves(test_true, test_probs, figures_dir / "roc_curves.png")
    F.plot_pr_curves(test_true, test_probs, figures_dir / "pr_curves.png")
    F.plot_error_flow(test_true, test_probs, figures_dir / "error_flow.png")
    F.plot_confidence_distributions(test_true, test_probs, figures_dir / "confidence_distributions.png")
    F.plot_reliability_diagram(test_true, test_probs, figures_dir / "reliability_diagram.png")
    F.plot_per_class_confidence_ecdf(test_true, test_probs, figures_dir / "per_class_confidence_ecdf.png")
    F.plot_bootstrap_distributions(boot, figures_dir / "bootstrap_distributions.png")
    F.plot_val_test_agreement(val_per_class, per_class, figures_dir / "val_test_agreement.png")
    F.plot_ours_vs_paper(metrics, boot, figures_dir / "ours_vs_paper.png")

    print("  writing tables...")
    train_split = pd.read_csv(split_dir / "train.csv")
    splits = {n: pd.read_csv(split_dir / f"{n}.csv") for n in ("train", "val", "test")}
    imbalance = T.imbalance_correction_table(train_split)
    split_fairness = T.split_fairness_table(splits)
    T.write_tables(
        {
            "headline_metrics": T.headline_table(metrics, boot, ece, brier),
            "per_class": T.per_class_markdown_table(per_class),
            "training_milestones": T.training_milestones_table(history, best_epoch),
            "split_fairness": split_fairness,
            "imbalance_correction": imbalance,
            "bootstrap": T.bootstrap_table(boot),
        },
        tables_dir,
    )

    checks = sanity_checks(test_true, test_probs, history, metrics)
    from src.eval.metrics import confusion_matrices
    counts, _ = confusion_matrices(test_true, test_probs)

    (out_dir / "summary.md").write_text(
        build_summary(metrics, boot, per_class, ece, brier, confidence, checks,
                      history, best_epoch, run_id, imbalance, split_fairness, counts),
        encoding="utf-8",
    )

    payload = {
        "run_id": run_id,
        "seed": seed,
        "checkpoint": checkpoint,
        "test": {
            **metrics,
            "ece_10bin_single_pass": ece,
            "brier": brier,
            **confidence,
            "bootstrap": boot.as_dict(),
            "per_class": per_class.to_dict(orient="records"),
        },
        "validation": val_metrics,
        "paper_reference": {
            "macro_auroc": F.PAPER_TEST_AUROC,
            "macro_f1": F.PAPER_TEST_F1,
            "mel_sensitivity": F.PAPER_MEL_SENSITIVITY,
            "mel_specificity": F.PAPER_MEL_SPECIFICITY,
            "nv_accuracy_eq17": F.PAPER_NV_ACCURACY,
            "note": "Paper values use T=50 MC Dropout with hair-removal/CLAHE preprocessing; "
                    "V1 is single-pass with no preprocessing. Not directly comparable.",
        },
        "sanity_checks": checks,
    }
    (out_dir / "metrics.json").write_text(
        json.dumps(payload, indent=2, default=_json_default), encoding="utf-8"
    )

    print(f"\nWrote {out_dir / 'summary.md'}, {out_dir / 'metrics.json'},")
    print(f"      13 figures in {figures_dir}, 6 tables in {tables_dir}")
    failed = [c for c in checks if not c["passed"]]
    print(f"Sanity checks: {len(checks) - len(failed)}/{len(checks)} pass"
          + ("" if not failed else f" — FAILED: {[c['check'] for c in failed]}"))


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the V1 evaluation suite (PLAN.md §5.3, Member C).")
    parser.add_argument("--inputs", type=Path, default=Path("results/v1/inputs"),
                        help="Dir with predictions_{val,test}.csv, history.csv, checkpoint.json")
    parser.add_argument("--out", type=Path, default=Path("results/v1"))
    parser.add_argument("--split-dir", type=Path, default=Path("data/splits"))
    parser.add_argument("--run-id", default="v1-b0-baseline")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--n-resamples", type=int, default=1000)
    args = parser.parse_args()

    run(args.inputs, args.out, args.run_id, args.seed, args.n_resamples, args.split_dir)


if __name__ == "__main__":
    main()
