        "missing two of its three accuracy-improving mechanisms. Macro F1 is "
        f"{abs(metrics['macro_f1'] - F.PAPER_TEST_F1):.4f} below, which is the expected V1 shortfall — see §5.",
        "",
        "## 2. Per-class results",
        "",
        T.per_class_markdown_table(per_class).to_markdown(index=False),
        "",
        "### The paper's ambiguous \"per-class accuracy\" is resolved",
        "",
        "PLAN.md §13 item 4 flagged that the paper's per-class accuracy could be either Eq. 17's",
        "one-vs-rest form (TP+TN)/N or plain recall, and asked us to report both.",
        "",
        f"For melanocytic nevus we measure **Eq. 17 = {nv['accuracy_eq17']:.3f}** and "
